/**
 * Look up a named character reference (without the `&` prefix and `;` suffix).
 * Returns the character(s) or null if not found.
 *
 * Per WHATWG § 13.5.1, the tokenizer tries matching the longest possible name.
 */
export function lookupNamedCharRef(name: string): string | null {
  return NAMED_CHAR_REFS.get(name) ?? null;
}

/**
 * Get the total number of named character references.
 */
export function getNamedCharRefCount(): number {
  return NAMED_CHAR_REFS.size;
}

/**
 * Check if a name exists in the named character references table.
 */
export function isNamedCharRef(name: string): boolean {
  return NAMED_CHAR_REFS.has(name);
}

export { NAMED_CHAR_REFS };
